/**
 * Storing generated PDFs (server side). Every generated document is kept as
 * a FinancialDocument with the SHA-256 of its bytes; the bytes are kept in
 * the database and served through /api/finance/documents/[id] after an
 * access check. The same document generated twice is stored once.
 */
import { createHash, randomUUID } from "node:crypto";
import { db } from "@/prisma/db";
import { and } from "@prisma/orm-postgres/orm-client";
import type { Numeric, TimestampString, Varchar } from "@prisma/orm-postgres/target/codec-types";
import { captureGeneratedPdf } from "@/lib/vault/sources";

const ts = (v: string) => v as unknown as TimestampString<3>;
const varchar = <N extends number>(v: string) => v as unknown as Varchar<N>;

export type GeneratedDocumentType = "LEVY_NOTICE" | "OWNER_STATEMENT" | "REMITTANCE_ADVICE" | "COMMITTEE_PACK" | "STATUTORY_PACK";

export const sha256 = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");

export async function storeGeneratedPdf(input: {
  schemeId: string;
  documentType: GeneratedDocumentType;
  fileName: string;
  bytes: Uint8Array;
  actorId: string;
  documentDate: string;
  amountCents?: number | null;
  lotId?: string | null;
  levyNoticeId?: string | null;
  supplierId?: string | null;
  supplierInvoiceId?: string | null;
  meetingId?: string | null;
}): Promise<{ id: string; hash: string; reused: boolean }> {
  const hash = sha256(input.bytes);
  const existing = await db.orm.public.FinancialDocument
    .where((d) => and(d.schemeId.eq(input.schemeId), d.documentType.eq(input.documentType), d.contentHash.eq(hash)))
    .first();
  if (existing) return { id: existing.id, hash, reused: true };

  const id = randomUUID();
  await db.transaction(async (tx) => {
    await tx.orm.public.FinancialDocument.create({
      id,
      schemeId: input.schemeId,
      documentType: input.documentType,
      uploadedBy: input.actorId,
      fileName: varchar<500>(input.fileName.slice(0, 500)),
      fileUrl: `/api/finance/documents/${id}`,
      fileSize: input.bytes.byteLength,
      mimeType: varchar<100>("application/pdf"),
      lotId: input.lotId ?? null,
      supplierId: input.supplierId ?? null,
      supplierInvoiceId: input.supplierInvoiceId ?? null,
      levyNoticeId: input.levyNoticeId ?? null,
      meetingId: input.meetingId ?? null,
      amount: input.amountCents == null ? null : (String(input.amountCents / 100) as unknown as Numeric<12, 2>),
      documentDate: ts(input.documentDate),
      documentStatus: "VERIFIED",
      verificationStatus: "MATCHED",
      contentHash: hash,
      reviewNotes: `Generated by StrataVerze. SHA-256 ${hash}.`,
    });
    await tx.orm.public.FinancialDocumentFile.create({
      financialDocumentId: id,
      contentBase64: Buffer.from(input.bytes).toString("base64"),
    });
  });
  // Into the building's vault, if it has one (trial). Never fails this.
  await captureGeneratedPdf({
    schemeId: input.schemeId,
    financialDocumentId: id,
    documentType: input.documentType,
    fileName: input.fileName,
    bytes: input.bytes,
    actorId: input.actorId,
    documentDate: input.documentDate,
  });
  return { id, hash, reused: false };
}

/**
 * Store an uploaded supplier invoice PDF the same way: bytes in the database
 * (not the public documents bucket), hashed, once per scheme. It stays
 * UNDER_REVIEW until an invoice is created from it.
 */
export async function storeUploadedInvoicePdf(input: { schemeId: string; fileName: string; bytes: Uint8Array; actorId: string }): Promise<{ id: string; hash: string; reused: boolean }> {
  const hash = sha256(input.bytes);
  const existing = await db.orm.public.FinancialDocument
    .where((d) => and(d.schemeId.eq(input.schemeId), d.documentType.eq("SUPPLIER_INVOICE"), d.contentHash.eq(hash)))
    .first();
  if (existing) return { id: existing.id, hash, reused: true };
  const id = randomUUID();
  await db.transaction(async (tx) => {
    await tx.orm.public.FinancialDocument.create({
      id,
      schemeId: input.schemeId,
      documentType: "SUPPLIER_INVOICE",
      uploadedBy: input.actorId,
      fileName: varchar<500>((input.fileName || "invoice.pdf").slice(0, 500)),
      fileUrl: `/api/finance/documents/${id}`,
      fileSize: input.bytes.byteLength,
      mimeType: varchar<100>("application/pdf"),
      documentStatus: "UNDER_REVIEW",
      verificationStatus: "PENDING",
      contentHash: hash,
      reviewNotes: `Uploaded for invoice entry. SHA-256 ${hash}.`,
    });
    await tx.orm.public.FinancialDocumentFile.create({
      financialDocumentId: id,
      contentBase64: Buffer.from(input.bytes).toString("base64"),
    });
  });
  return { id, hash, reused: false };
}

/** The stored bytes of a generated document, or null. */
export async function loadGeneratedPdf(documentId: string) {
  const [doc, file] = await Promise.all([
    db.orm.public.FinancialDocument.where((d) => d.id.eq(documentId)).first(),
    db.orm.public.FinancialDocumentFile.where((f) => f.financialDocumentId.eq(documentId)).first(),
  ]);
  if (!doc || !file) return null;
  return { doc, bytes: new Uint8Array(Buffer.from(file.contentBase64, "base64")) };
}
